
'use strict';

const { db } = require('../config/firebase');
const geminiService = require('../services/ai/gemini.service');

const {
  FacebookError,
  cleanString
} = require('./facebook.utils');

const PRODUCTS_COLLECTION = 'products';

// ========================================
// Helpers
// ========================================

function getAvailableVariants(variants) {
  if (!Array.isArray(variants)) {
    return [];
  }

  return variants
    .filter(variant => (
      variant &&
      variant.isActive === true &&
      Number.isSafeInteger(Number(variant.stock)) &&
      Number(variant.stock) > 0
    ))
    .map(variant => ({
      color: cleanString(variant.color, 100),
      size: cleanString(variant.size, 100),
      stock: Number(variant.stock),
      sellingPrice:
        Number.isFinite(Number(variant.sellingPrice)) &&
        variant.sellingPrice !== null &&
        variant.sellingPrice !== ''
          ? Number(variant.sellingPrice)
          : null
    }));
}

function formatMoney(value) {
  return `৳${Number(value).toLocaleString('en-BD')}`;
}

// ========================================
// Load Product
// ========================================

async function getFacebookProduct(productId) {
  const id = cleanString(productId, 128);

  if (!id) {
    throw new FacebookError(
      'Product ID is required.',
      400,
      'PRODUCT_ID_REQUIRED'
    );
  }

  const snapshot = await db
    .collection(PRODUCTS_COLLECTION)
    .doc(id)
    .get();

  if (!snapshot.exists) {
    throw new FacebookError(
      'Product not found.',
      404,
      'PRODUCT_NOT_FOUND'
    );
  }

  const product = snapshot.data() || {};

  if (
    product.active !== true ||
    product.status !== 'active' ||
    product.deleted !== false ||
    product.summary?.hasStock !== true
  ) {
    throw new FacebookError(
      'This product is not eligible for Facebook posting.',
      400,
      'PRODUCT_NOT_ELIGIBLE'
    );
  }

  const variants = getAvailableVariants(product.variants);

  if (!variants.length) {
    throw new FacebookError(
      'No active variant with available stock.',
      400,
      'PRODUCT_OUT_OF_STOCK'
    );
  }

  return {
    id: snapshot.id,
    name: cleanString(product.name, 300),
    sku: cleanString(product.sku, 100),
    shortDescription: cleanString(
      product.shortDescription,
      1000
    ),
    description: cleanString(
      product.description,
      2000
    ),
    variants
  };
}

// ========================================
// Generate Facebook Caption
// ========================================

async function generateFacebookCaption(productId) {
  const product = await getFacebookProduct(productId);

  if (!product.name) {
    throw new FacebookError(
      'Product name is missing.',
      400,
      'PRODUCT_NAME_REQUIRED'
    );
  }

  const factualVariants = product.variants.map(variant => ({
    color: variant.color || 'Default',
    size: variant.size || 'Standard',
    stock: variant.stock
  }));

  const result = await geminiService.generateText({
    systemInstruction: [
      'You are a professional Facebook fashion copywriter for a Bangladeshi clothing store.',
      'Write an attractive, natural promotional caption.',
      'Write Bangla first and English second.',
      'Use only the supplied product facts.',
      'Do not invent fabric, material, features, measurements, discounts, guarantees or product claims.',
      'Do not generate prices, stock numbers, variant names or availability information.',
      'Do not include hashtags unless they are directly relevant and factual.',
      'Keep the caption concise and suitable for a Facebook Page.',
      'Return only the caption text, without markdown or explanations.'
    ].join(' '),

    prompt: [
      'Create a promotional Facebook caption for this product.',
      '',
      `Product name: ${product.name}`,
      `Short description: ${product.shortDescription || 'Not provided'}`,
      `Description: ${product.description || 'Not provided'}`,
      `Available variants: ${JSON.stringify(factualVariants)}`
    ].join('\n'),

    temperature: 0.55,
    maxOutputTokens: 700
  });

  const marketingText = cleanString(result.text, 2500);

  if (!marketingText) {
    throw new FacebookError(
      'Gemini returned an empty caption.',
      502,
      'EMPTY_AI_CAPTION'
    );
  }

  // Prices and stock are always generated by backend,
  // never by Gemini.

  const variantLines = product.variants.map(variant => {
    const color = variant.color || 'Default';
    const size = variant.size || 'Standard';

    const price = variant.sellingPrice !== null
      ? formatMoney(variant.sellingPrice)
      : 'Price unavailable';

    return `${color} / ${size} — ${price} | `;
  });

  const caption = [
    marketingText,
    '',
    'Available Variants:',
    ...variantLines
  ].join('\n');

  return {
    success: true,
    productId: product.id,
    productName: product.name,
    caption,
    variants: product.variants,
    model: result.model
  };
}

// ========================================
// Exports
// ========================================

module.exports = {
  getFacebookProduct,
  generateFacebookCaption
};
