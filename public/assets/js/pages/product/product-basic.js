
'use strict';

import { createElement } from '../../helpers.js';

// ========================================
// CONFIGURATION
// ========================================

const PRODUCT_FIELDS = {
  name: {
    id: 'product-name',
    label: 'Product Name',
    placeholder: 'Enter product name',
    required: true,
    maxLength: 150
  },

  brand: {
    id: 'product-brand',
    label: 'Brand',
    placeholder: 'Enter brand name',
    required: true,
    maxLength: 100
  },

  productCode: {
    id: 'product-code',
    label: 'Product Code',
    placeholder: 'Auto generated',
    readonly: true
  },

  barcode: {
    id: 'product-barcode',
    label: 'Barcode',
    placeholder: 'Leave blank to auto-generate',
    helpText: 'A unique barcode will be generated when this field is empty.',
    maxLength: 100
  },

  sku: {
    id: 'product-sku',
    label: 'SKU',
    placeholder: 'Auto generated',
    readonly: true
  }
};

const DEFAULT_BRAND = 'Nishat Fashion';
const MAX_SLUG_LENGTH = 150;

// ========================================
// SAFE VALUE
// ========================================

function toSafeString(value) {
  if (value === null || value === undefined) {
    return '';
  }

  if (
    typeof value === 'object' ||
    typeof value === 'function'
  ) {
    return '';
  }

  return String(value).trim();
}

// ========================================
// CREATE FIELD
// ========================================

function createField(fieldName, config, value = '') {
  const wrapper = createElement('div', {
    className: 'form-group product-basic-field'
  });

  const label = createElement('label', {
    text: config.label,
    attributes: {
      for: config.id
    }
  });

  const input = createElement('input', {
    className: 'form-control',
    attributes: {
      type: 'text',
      id: config.id,
      name: fieldName,
      placeholder: config.placeholder,
      maxlength: config.maxLength || 180,
      autocomplete: 'off',
      required: Boolean(config.required),
      readonly: Boolean(config.readonly)
    },
    dataset: {
      productField: fieldName
    }
  });

  input.value = toSafeString(value);

  wrapper.append(
    label,
    input
  );

  if (config.readonly || config.helpText) {
    const helpText = createElement('small', {
      className: 'form-help',
      text: config.helpText || 'Automatically generated by the server.'
    });

    wrapper.append(helpText);
  }

  return wrapper;
}

// ========================================
// RENDER PRODUCT BASIC INFORMATION
// ========================================

export function renderProductBasic(product = {}) {
  if (
    !product ||
    typeof product !== 'object' ||
    Array.isArray(product)
  ) {
    product = {};
  }

  const section = createElement('section', {
    className: 'product-form-section product-basic-section',
    attributes: {
      id: 'product-basic-section'
    }
  });

  const header = createElement('div', {
    className: 'product-section-header'
  });

  const title = createElement('h3', {
    text: 'Basic Information'
  });

  const description = createElement('p', {
    text: 'Enter the basic information of your product.'
  });

  header.append(
    title,
    description
  );

  const fieldsContainer = createElement('div', {
    className: 'product-basic-grid'
  });

  const fields = [
    'name',
    'brand',
    'productCode',
    'barcode',
    'sku'
  ];

  fields.forEach(fieldName => {
    const config = PRODUCT_FIELDS[fieldName];

    const defaultValue =
      fieldName === 'brand'
        ? DEFAULT_BRAND
        : '';

    const value =
      product[fieldName] !== undefined &&
      product[fieldName] !== null
        ? product[fieldName]
        : defaultValue;

    fieldsContainer.append(
      createField(fieldName, config, value)
    );
  });

  section.append(
    header,
    fieldsContainer
  );

  return section;
}

// ========================================
// SLUG GENERATOR
// ========================================

export function generateProductSlug(value = '') {
  const normalized = toSafeString(value)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');

  return normalized
    .slice(0, MAX_SLUG_LENGTH)
    .replace(/-+$/g, '');
}

// ========================================
// CREATE UNIQUE SLUG
// ========================================

function createUniqueSlug(
  value,
  existingSlugs = [],
  currentSlug = ''
) {
  const base = generateProductSlug(value) || 'product';

  const current = toSafeString(currentSlug).toLowerCase();

  const reserved = new Set(
    existingSlugs
      .map(slug => toSafeString(slug).toLowerCase())
      .filter(slug => slug && slug !== current)
  );

  if (!reserved.has(base)) {
    return base;
  }

  let suffix = 2;
  let candidate = '';

  do {
    const suffixText = `-${suffix}`;
    const availableLength =
      MAX_SLUG_LENGTH - suffixText.length;

    const trimmedBase = base
      .slice(0, availableLength)
      .replace(/-+$/g, '');

    candidate = `${trimmedBase}${suffixText}`;

    suffix += 1;
  } while (reserved.has(candidate));

  return candidate;
}

// ========================================
// BIND PRODUCT BASIC EVENTS
// ========================================

export function bindProductBasicEvents(
  container,
  options = {}
) {
  if (!container || typeof container.querySelector !== 'function') {
    console.warn('[PRODUCT BASIC] Invalid container.');
    return () => {};
  }

  const nameInput = container.querySelector(
    '[data-product-field="name"]'
  );

  const slugInput = container.querySelector(
    '#product-slug'
  );

  if (!nameInput || !slugInput) {
    console.warn('[PRODUCT BASIC] Name or slug field not found.');
    return () => {};
  }

  const existingSlugs = Array.isArray(options.existingSlugs)
    ? options.existingSlugs
        .map(toSafeString)
        .filter(Boolean)
    : [];

  const initialSlug = toSafeString(
    options.currentSlug || slugInput.value
  );

  slugInput.readOnly = true;

  slugInput.dataset.existingSlugs = JSON.stringify(
    existingSlugs
  );

  slugInput.dataset.currentSlug = initialSlug;

  function handleNameInput() {
    const name = toSafeString(nameInput.value);

    slugInput.value = name
      ? createUniqueSlug(
          name,
          existingSlugs,
          initialSlug
        )
      : '';

    slugInput.dispatchEvent(
      new Event('input', {
        bubbles: true
      })
    );
  }

  nameInput.addEventListener(
    'input',
    handleNameInput
  );

  if (!slugInput.value && nameInput.value.trim()) {
    handleNameInput();
  }

  let cleaned = false;

  return function cleanup() {
    if (cleaned) return;

    cleaned = true;

    nameInput.removeEventListener(
      'input',
      handleNameInput
    );
  };
}

// ========================================
// GET PRODUCT BASIC DATA
// ========================================

export function getProductBasicData(container) {
  const data = {};

  if (!container || typeof container.querySelector !== 'function') {
    return data;
  }

  Object.keys(PRODUCT_FIELDS).forEach(fieldName => {
    const input = container.querySelector(
      `[data-product-field="${fieldName}"]`
    );

    data[fieldName] = input
      ? toSafeString(input.value)
      : '';
  });

  return data;
}

// ========================================
// SET PRODUCT BASIC DATA
// ========================================

export function setProductBasicData(
  product = {},
  container
) {
  if (
    !container ||
    typeof container.querySelector !== 'function'
  ) {
    return;
  }

  if (
    !product ||
    typeof product !== 'object' ||
    Array.isArray(product)
  ) {
    return;
  }

  Object.keys(PRODUCT_FIELDS).forEach(fieldName => {
    const input = container.querySelector(
      `[data-product-field="${fieldName}"]`
    );

    if (!input) return;

    if (
      Object.prototype.hasOwnProperty.call(
        product,
        fieldName
      )
    ) {
      input.value = toSafeString(product[fieldName]);
    }
  });
}

// ========================================
// EXPORTS
// ========================================

export default {
  renderProductBasic,
  generateProductSlug,
  bindProductBasicEvents,
  getProductBasicData,
  setProductBasicData
};
